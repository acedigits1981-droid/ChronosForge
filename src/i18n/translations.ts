export function getLanguageDir(lang: LanguageCode): 'ltr' | 'rtl' {
  return SUPPORTED_LANGUAGES.find((l) => l.code === lang)?.dir ?? 'ltr';
}

export type EasyPresetFilter =
  | 'round-all'
  | 'round-analog'
  | 'round-digital'
  | 'square-all'
  | 'square-analog'
  | 'square-digital';

export function classifyEasyPreset(
  preset: WatchFaceConfig
): 'round-analog' | 'round-digital' | 'square-analog' | 'square-digital' {
  if (
    preset.category === 'round-analog' ||
    preset.category === 'round-digital' ||
    preset.category === 'square-analog' ||
    preset.category === 'square-digital'
  ) {
    return preset.category;
  }
  const isRound = preset.resolution.shape === 'round';
  const isDigital =
    preset.displayMode === 'digital' || preset.displayMode === 'hybrid';
  return isRound
    ? isDigital
      ? 'round-digital'
      : 'round-analog'
    : isDigital
    ? 'square-digital'
    : 'square-analog';
}

export function simplifyPresetDisplayName(name: string): string {
  return name
    .replace(/\s*\(Round\)/gi, '')
    .replace(/\s*\(Square\)/gi, '')
    .replace(/\s*\(FHD\)/gi, '')
    .replace(/\s*\(Squircle\)/gi, '')
    .replace(/\s*\(Square FHD\)/gi, '')
    .trim();
}
